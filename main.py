# Словарь молодежного сленга
meme_dict = {
    "кринж": "что-то очень странное или стыдное", 
    "лол": "очень смешно", 
    "рофл": "шутка", 
    "щищ": "одобрение или восторг",
    "криповый": "страшный, пугающий",
    "агриться": "злиться, проявлять агрессию"
}

# Словарь старого сленга и крылатых выражений
old_dict = {
    "клёво": "отлично, замечательно",
    "шнурки в стакане": "родители дома",
    "чувак": "парень, молодой человек",
    "дойти до ручки": "опуститься, дойти до крайности или нищеты",
    "бить баклуши": "бездельничать, заниматься ерундой",
    "зарубить на носу": "хорошо и навсегда запомнить",
    "дело в шляпе": "всё идет отлично, вопрос успешно решен",
    "шерочка с машерочкой": "две неразлучные подруги"
}

print("Перевод с разных слэнгов. Если хотите перевод с молодежного слэнга, нажмите 1. Если со старого слэнга, нажмите 2:") 
w = input() 

# Проверяем выбор пользователя
if w == "1": 
    word = input("Введите непонятное молодежное слово: ").lower()
    
    if word in meme_dict:
        print("Слово", word, "означает:", meme_dict[word])
    else:
        print("Такого слова нет в молодежном словаре.")

elif w == "2":
    word = input("Введите непонятное старое выражение: ").lower()
    
    if word in old_dict:
        print("Выражение", word, "означает:", old_dict[word])
    else:
        print("Такого слова или выражения нет в старом словаре.")

else:
    print("Неверный выбор. Пожалуйста, введите 1 или 2.")
